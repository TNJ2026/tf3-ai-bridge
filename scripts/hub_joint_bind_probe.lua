-- Experimental preview-only adapter. Derive candidate ports from THIS proposal.
-- No historical/generated ID constants. No world command is submitted.
local explicit={};for _,n in ipairs(nodes)do explicit[n.entity]=true end
for _,e in ipairs(edges)do explicit[e.entity]=true end
local adjacency={};local stationRole={}
for id,net in pairs(pd.entity2tn)do
 local person,cargo,bus,car=false,false,false,false
 for _,e in ipairs(net.edges)do
  person=person or e.transportModes[0];cargo=cargo or e.transportModes[1]
  bus=bus or e.transportModes[3];car=car or e.transportModes[2]
  if e.transportModes[2]or e.transportModes[3]or e.transportModes[4]then
   local a,b=e.conns[1].entity,e.conns[2].entity
   if a~=b then adjacency[a]=adjacency[a]or{};adjacency[b]=adjacency[b]or{};adjacency[a][b]=true;adjacency[b][a]=true end
  end
 end
 if id<0 and not explicit[id]and bus and not car then
  if cargo and not person then stationRole[id]='truck'elseif person and not cargo then stationRole[id]='bus'end
 end
end
local candidates={bus={},truck={},road_depot={}};local candidateSets={bus={},truck={}}
for id,neighbors in pairs(adjacency)do if id<0 and not explicit[id]and not stationRole[id]then
 local count,internal=0,nil;for v in pairs(neighbors)do count=count+1;internal=v end
 if count<=2 then for internal in pairs(neighbors)do if internal<0 and not explicit[internal]and not stationRole[internal]then
  for st in pairs(adjacency[internal]or{})do local role=stationRole[st]
   if role and not candidateSets[role][id]then candidates[role][#candidates[role]+1]=id;candidateSets[role][id]=true end
  end
 end end
 end
end end
local remap={};local bindings={}
if spec.portBindings.road_depot then
 local p=point(assert(spec.portBindings.road_depot.expectedLocalPort,'Missing depot external-port geometry'));local seen={}
 for id,net in pairs(pd.entity2tn)do if not explicit[id]then for _,e in ipairs(net.edges)do
  if e.transportModes[2]and e.transportModes[3]and e.transportModes[4]and e.geometry and e.geometry.cubicSpline then for k=1,2 do
   local n=e.conns[k].entity;local q=e.geometry.cubicSpline.pos[k]
   if n<0 and not explicit[n]and math.abs(q.x-p.x)<.05 and math.abs(q.y-p.y)<.05 and not seen[n]then
    seen[n]=true;candidates.road_depot[#candidates.road_depot+1]=n
   end
  end end
 end end end
end
for _,role in ipairs({'bus','truck','road_depot'})do
 if spec.portBindings[role]then
 assert(#candidates[role]==1,'Generated port ambiguous for '..role..'; candidates='..tostring(#candidates[role])..'; proposal='..B.json.encode({critical=pd.errorState.critical,messages=B.toPlain(pd.errorState.messages),warnings=B.toPlain(pd.errorState.warnings),infos=B.toPlain(pd.errorState.infos)}))
 local from,to=spec.portBindings[role].roadNode,candidates[role][1]
 assert(not explicit[to]and from~=to,'Port must be generated by current proposal')
 assert(not remap[from]or remap[from]==to,'Shared template port did not resolve to one native node; redesign shared entrance')
 remap[from]=to;bindings[role]={roadNode=from,nativeEntranceNode=to,verified=false}
 if spec.alignGeneratedPortGeometry then
  local measured=nil
  for id,net in pairs(pd.entity2tn)do if not explicit[id]then
   for _,edge in ipairs(net.edges)do if edge.transportModes[4]then
    for k=1,2 do if edge.conns[k].entity==to and edge.conns[3-k].entity~=to then
     -- Native entrance lanes expose the centre spline and endpoint heights.
     local q=edge.geometry.cubicSpline.pos[k];local h=k==1 and edge.geometry.height.x or edge.geometry.height.y
     local p={x=q.x,y=q.y,z=h}
     if measured then assert(math.abs(p.x-measured.x)<.01 and math.abs(p.y-measured.y)<.01 and math.abs(p.z-measured.z)<.01,'Ambiguous native entrance geometry')else measured=p end
    end end
   end end
  end end
  assert(measured,'Native entrance geometry unavailable');bindings[role].nativePosition=measured
  -- Frontage is a planned shared constraint, not a movable entrance stub.
  -- Moving it changes maintenance clearance, walking links and other entrances.
  for _,row in ipairs(spec.roads or{})do if row.buildPhase=='frontage' then
   for _,edge in ipairs(edges)do if edge.entity==row.entity then
    local c=edge.comp
    local p=c.node0==from and c.position0 or c.node1==from and c.position1 or nil
    if p then
     local dx,dy=p.x-measured.x,p.y-measured.y
     assert(dx*dx+dy*dy<=0.01,string.format('Native port would move fixed frontage: %s; planned=(%.6f,%.6f), native=(%.6f,%.6f), facility correction=(%.6f,%.6f); redesign facility or explicit entrance before submission',role,p.x,p.y,measured.x,measured.y,dx,dy))
    end
   end end
  end end
  for _,edge in ipairs(edges)do
   local c=edge.comp;local changed=false
   if c.node0==from then c.position0=V3(measured.x,measured.y,measured.z);changed=true end
   if c.node1==from then c.position1=V3(measured.x,measured.y,measured.z);changed=true end
   if changed then
    local a,b=c.position0,c.position1;local dx,dy,dz=b.x-a.x,b.y-a.y,b.z-a.z
    assert(dx*dx+dy*dy>=4,'Native entrance collapses road')
    c.tangent0=V3(dx,dy,c.node0==from and 0 or dz)
    c.tangent1=V3(dx,dy,c.node1==from and 0 or dz)
   end
  end
 end
 end
end
local remaining={};for _,n in ipairs(nodes)do if not remap[n.entity]then remaining[#remaining+1]=n end end
for _,e in ipairs(edges)do
 if remap[e.comp.node0]then e.comp.node0=remap[e.comp.node0]end
 if remap[e.comp.node1]then e.comp.node1=remap[e.comp.node1]end
end
proposal.streetProposal.nodesToAdd=remaining;proposal.streetProposal.edgesToAdd=edges
pd=api.engine.util.proposal.makeProposalData(proposal,context)
for _,binding in pairs(bindings)do assert(pd.entity2tn[binding.nativeEntranceNode],'Generated port identity changed after rebind')end
spec.portBindings=bindings
